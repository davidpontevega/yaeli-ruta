// Colored initials tile at the start of a list row: gives each person/supplier a face and makes lists scannable.
const TONES = [
  "bg-teal-100 text-teal-800",
  "bg-sky-100 text-sky-800",
  "bg-amber-100 text-amber-800",
  "bg-violet-100 text-violet-800",
  "bg-rose-100 text-rose-800",
  "bg-lime-100 text-lime-800",
] as const;

const initials = (name: string) =>
  name
    .replace(/[^\p{L}\p{N}\s]/gu, "")
    .trim()
    .split(/\s+/)
    .slice(0, 2)
    .map((w) => w[0])
    .join("")
    .toUpperCase() || "·";

/** Same name → same color, so a customer keeps its color across screens. */
const toneOf = (name: string) => TONES[[...name].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7) % TONES.length];

export function Avatar({ name, tone, size = "md" }: { name: string; tone?: string; size?: "sm" | "md" }) {
  return (
    <span
      aria-hidden
      className={`font-display flex shrink-0 items-center justify-center rounded-xl font-bold ${size === "sm" ? "h-8 w-8 text-xs" : "h-10 w-10 text-sm"} ${tone ?? toneOf(name)}`}
    >
      {initials(name)}
    </span>
  );
}

/** Icon tile (same size as Avatar) for rows that are things, not people: routes, purchases, orders. */
export function IconTile({ d, tone = "bg-teal-50 text-teal-700" }: { d: string; tone?: string }) {
  return (
    <span aria-hidden className={`flex h-10 w-10 shrink-0 items-center justify-center rounded-xl ${tone}`}>
      <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
        <path d={d} />
      </svg>
    </span>
  );
}

